if __name__ == '__main__':
    # Integer variable
    zahl = 10
    print("Integer variable:", zahl)
    print("Type:", type(zahl))

    # Floating-point variable
    kommazahl = 10.5
    print("Floating-point variable:", kommazahl)
    print("Type:", type(kommazahl))

    # String variable
    text = "Hello, World!"
    print("String variable:", text)
    print("Type:", type(text))

    # Boolean variable
    wahrheitswert = True
    print("Boolean variable:", wahrheitswert)
    print("Type:", type(wahrheitswert))